import { useState } from 'react';
import { View } from 'react-native';
import { router, useLocalSearchParams } from 'expo-router';
import { Download, Receipt, Send } from 'lucide-react-native';
import { EmptyState, Gutter, KeyValue, Screen, ScreenHeader, SectionHeader, cardListStyle } from '@/components/Layout';
import { StatusChip } from '@/components/Chips';
import { Card } from '@/components/Surface';
import { Button } from '@/components/Button';
import { Confirm } from '@/components/Form';
import { ProgressBar } from '@/components/Progress';
import { Txt } from '@/components/Txt';
import { useToast } from '@/components/Toast';
import { PaymentRow } from '@/features/cards';
import { RecordPaymentSheet } from '@/features/sheets';
import { useStore } from '@/store/DemoStore';
import { useMe } from '@/store/Session';
import { useColors } from '@/theme/ThemeProvider';
import { findClient, findProject, invoiceBalance, invoiceTotals } from '@/lib/selectors';
import { fmtDate, inr } from '@/lib/format';

export default function InvoiceDetail() {
  const c = useColors();
  const { id } = useLocalSearchParams<{ id: string }>();
  const { state, actions } = useStore();
  const { user, role } = useMe();
  const toast = useToast();
  const [paying, setPaying] = useState(false);
  const [confirm, setConfirm] = useState<null | 'issue' | 'void'>(null);
  const inv = state.invoices.find((i) => i.id === id);
  if (!inv || role === 'team' || (role === 'client' && (inv.clientId !== user.clientId || inv.status === 'draft'))) {
    return (
      <Screen header={<ScreenHeader title="Invoice" />}>
        <EmptyState icon={Receipt} title="Invoice not available" />
      </Screen>
    );
  }
  const client = findClient(state, inv.clientId);
  const project = findProject(state, inv.projectId);
  const totals = invoiceTotals(inv);
  const b = invoiceBalance(state, inv);
  const paidPct = b.total ? (100 * b.paid) / b.total : 0;

  const pdf = () => toast('Demo build: the PDF is generated by the API after integration.');
  const footer =
    inv.status === 'draft' && role === 'admin' ? (
      <Button label="Issue to client" icon={Send} full onPress={() => setConfirm('issue')} />
    ) : inv.status === 'issued' && b.balance > 0 ? (
      <View style={{ flexDirection: 'row', gap: 10 }}>
        <Button label="PDF" icon={Download} variant="ghost" onPress={pdf} />
        <Button label={role === 'admin' ? 'Record payment' : 'I have paid'} style={{ flex: 1 }} onPress={() => setPaying(true)} />
      </View>
    ) : (
      <Button label="Download PDF" icon={Download} variant="ghost" full onPress={pdf} />
    );

  return (
    <Screen header={<ScreenHeader title={inv.number} eyebrow={role === 'admin' ? client?.company : 'Invoice'} />} footer={footer}>
      <Gutter style={{ paddingTop: 24, gap: 14 }}>
        <Card glass brackets padding={22}>
          <View style={{ flexDirection: 'row', justifyContent: 'space-between', alignItems: 'center' }}>
            <Txt variant="mono" tone="muted">
              {b.state === 'paid' ? 'Paid in full' : 'Balance due'}
            </Txt>
            <StatusChip status={b.state} />
          </View>
          <Txt variant="amount" style={{ marginTop: 10 }}>
            <Txt variant="amount" tone="gold">
              ₹
            </Txt>
            {inr(b.state === 'paid' ? b.total : b.balance).slice(1)}
          </Txt>
          <View style={{ marginTop: 16 }}>
            <ProgressBar value={paidPct} label="Paid" />
          </View>
          <Txt variant="bodySm" tone="muted" style={{ marginTop: 8 }}>
            {`${inr(b.paid)} of ${inr(b.total)} verified`}
          </Txt>
          {b.pending ? (
            <Txt variant="caption" tone="gold" style={{ marginTop: 4 }}>
              {`${inr(b.pending)} awaiting verification`}
            </Txt>
          ) : null}
          <View style={{ flexDirection: 'row', gap: 10, marginTop: 18 }}>
            <KeyValue label="Issued" value={inv.issueDate ? fmtDate(inv.issueDate, true) : 'Draft'} />
            <KeyValue label="Due" value={fmtDate(inv.dueDate, true)} tone={b.state === 'overdue' ? 'danger' : 'fg'} />
          </View>
        </Card>

        <Card>
          <Txt variant="monoSm" tone="faint">
            {project ? `${project.name}` : 'General'}
          </Txt>
          <Txt variant="title" style={{ marginTop: 6 }}>
            {inv.title}
          </Txt>
          <View style={{ marginTop: 14 }}>
            {inv.items.map((it, i) => (
              <View key={i} style={{ flexDirection: 'row', justifyContent: 'space-between', gap: 12, paddingVertical: 12, borderTopWidth: 1, borderTopColor: c.line }}>
                <View style={{ flex: 1 }}>
                  <Txt variant="bodySm" weight="medium">
                    {it.description}
                  </Txt>
                  <Txt variant="caption" tone="faint">{`${it.quantity} × ${inr(it.unitPrice)} · GST ${it.taxRate}%`}</Txt>
                </View>
                <Txt variant="bodySm" weight="semibold">
                  {inr(it.quantity * it.unitPrice)}
                </Txt>
              </View>
            ))}
            {[
              ['Subtotal', totals.subtotal],
              ['GST', totals.tax],
            ].map(([l, v]) => (
              <View key={l as string} style={{ flexDirection: 'row', justifyContent: 'space-between', paddingVertical: 8, borderTopWidth: 1, borderTopColor: c.line }}>
                <Txt variant="bodySm" tone="muted">
                  {l as string}
                </Txt>
                <Txt variant="bodySm">{inr(v as number)}</Txt>
              </View>
            ))}
            <View style={{ flexDirection: 'row', justifyContent: 'space-between', paddingTop: 12, borderTopWidth: 1, borderTopColor: c.lineStrong }}>
              <Txt variant="title">Total</Txt>
              <Txt variant="title" tone="gold">
                {inr(totals.total)}
              </Txt>
            </View>
          </View>
          {inv.notes ? (
            <Txt variant="caption" tone="faint" style={{ marginTop: 14 }}>
              {inv.notes}
            </Txt>
          ) : null}
        </Card>
        {role === 'admin' && inv.status === 'issued' && b.paid === 0 ? (
          <Button label="Void invoice" variant="quiet" size="sm" onPress={() => setConfirm('void')} />
        ) : null}
      </Gutter>

      <SectionHeader label={`Payments · ${b.payments.length}`} style={{ marginTop: 30 }} />
      <Gutter style={{ marginTop: 14 }}>
        {b.payments.length ? (
          <Card style={cardListStyle}>
            {b.payments.map((p, i) => (
              <PaymentRow key={p.id} payment={p} last={i === b.payments.length - 1} onPress={role === 'admin' ? () => router.push(`/payment/${p.id}`) : undefined} />
            ))}
          </Card>
        ) : (
          <EmptyState icon={Receipt} title="No payments yet" body={role === 'client' ? 'After paying by UPI, bank transfer or cash, tap “I have paid”.' : 'Recorded and client-submitted payments appear here.'} />
        )}
      </Gutter>

      {paying ? <RecordPaymentSheet visible onClose={() => setPaying(false)} invoiceId={inv.id} /> : null}
      <Confirm
        visible={confirm === 'issue'}
        title="Issue this invoice?"
        body={`${client?.company} will be notified and can see ${inv.number} in their portal.`}
        confirmLabel="Issue"
        onCancel={() => setConfirm(null)}
        onConfirm={() => {
          actions.issueInvoice(inv.id);
          toast('Invoice issued');
          setConfirm(null);
        }}
      />
      <Confirm
        visible={confirm === 'void'}
        title="Void this invoice?"
        body="A void invoice stays on record but can no longer be paid."
        confirmLabel="Void"
        danger
        onCancel={() => setConfirm(null)}
        onConfirm={() => {
          actions.voidInvoice(inv.id);
          toast('Invoice voided');
          setConfirm(null);
        }}
      />
    </Screen>
  );
}
